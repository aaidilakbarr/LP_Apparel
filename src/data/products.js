export const formatRupiah = (value) =>
  new Intl.NumberFormat('id-ID', {
    style: 'currency',
    currency: 'IDR',
    maximumFractionDigits: 0,
  }).format(value)

export const formatPrice = (item, currencyMode = 'IDR') => {
  if (currencyMode === 'USD' && item?.priceUsd) {
    return `$${item.priceUsd.toFixed(2)}`
  }
  const val = typeof item === 'number' ? item : item?.price ?? 0
  return formatRupiah(val)
}
